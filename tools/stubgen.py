"""Generate stub DLLs for every import of an executable that nothing else provides (a first start
attempt of a title against generated stubs).

A module is "provided" when it exists in the title directory, in Wine's x86_64-windows directory,
or in --provided directories (e.g. the layer's build). For each other module a DLL is generated:
  - imports also exported by a --forward module are forwarded to it (e.g. kernelx -> kernel32);
  - everything else is a stub that logs "[stub] module!name" (first few calls) and returns 0.
Ordinal-only imports are exported by ordinal. The output directory receives <module>.dll files
plus stubgen-report.txt. Generated DLLs belong in a run directory, never in the repository.

Usage: stubgen.py <exe> <outdir> [--provided DIR]... [--forward MOD.dll=FALLBACK.dll[,FALLBACK2.dll]]...
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
from collections import OrderedDict
from pathlib import Path

XWIN = Path(os.environ.get("XWIN_ROOT", Path.home() / ".xwin"))


def imports(exe):
    out = subprocess.run(["llvm-readobj", "--coff-imports", str(exe)], capture_output=True, text=True).stdout
    mods, cur = OrderedDict(), None
    for line in out.splitlines():
        m = re.search(r"Name: (\S+\.dll)", line, re.I)
        if m:
            cur = m.group(1)
            mods.setdefault(cur, [])
            continue
        m = re.search(r"Symbol: (\S*) \((\d+)\)", line)
        if m and cur:
            mods[cur].append((m.group(1), int(m.group(2))))
    return mods


def exports(dll):
    out = subprocess.run(["llvm-readobj", "--coff-exports", str(dll)], capture_output=True, text=True).stdout
    return set(re.findall(r"Name: (\S+)", out))


def find(name, dirs):
    for d in dirs:
        for f in Path(d).glob("*"):
            if f.name.lower() == name.lower():
                return f
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("exe")
    ap.add_argument("out")
    ap.add_argument("--provided", action="append", default=[])
    ap.add_argument("--forward", action="append", default=[])
    ap.add_argument("--wine-dir", default=str(Path(shutil.which("wine")).resolve().parent.parent / "lib/wine/x86_64-windows"))
    a = ap.parse_args()
    exe, out = Path(a.exe), Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    search = [exe.parent, a.wine_dir] + a.provided
    forwards = {}
    for f in a.forward:
        mod, fb = f.split("=")
        forwards[mod.lower()] = [find(x, [a.wine_dir] + a.provided) or x for x in fb.split(",")]
    report = []
    for mod, syms in imports(exe).items():
        if find(mod, search):
            continue
        fallback = [(Path(str(f)).stem, exports(f)) for f in forwards.get(mod.lower(), []) if Path(str(f)).exists()]
        lines, defs, n_fwd, n_stub = [], [], 0, 0
        for i, (name, ordinal) in enumerate(syms):
            target = next((stem for stem, ex in fallback if name and name in ex), None)
            if target:
                defs.append(f"    {name}={target}.{name}")
                n_fwd += 1
                continue
            label = name or f"#{ordinal}"
            lines.append(f'XSL_STUB({i}, "{mod}!{label}")')
            defs.append(f"    {name}=xsl_stub_{i} @{ordinal}" if name else f"    xsl_ord_{ordinal}=xsl_stub_{i} @{ordinal} NONAME")
            n_stub += 1
        stem = Path(mod).stem
        c = out / f"{stem}.c"
        c.write_text('''// Generated by tools/stubgen.py. Do not commit.
#include <windows.h>
static void hit(const char* what, volatile LONG* n) {
    if (InterlockedIncrement(n) > 3) return;
    char buf[512];
    int len = wsprintfA(buf, "[stub] %s\\n", what);
    DWORD w;
    WriteFile(GetStdHandle(STD_ERROR_HANDLE), buf, len, &w, NULL);
    OutputDebugStringA(buf);
}
#define XSL_STUB(i, what) static volatile LONG xsl_n_##i; __declspec(noinline) void* xsl_stub_##i(void) { hit(what, &xsl_n_##i); return 0; }
''' + "\n".join(lines) + "\nBOOL WINAPI DllMain(HINSTANCE h, DWORD r, LPVOID p) { return TRUE; }\n")
        d = out / f"{stem}.def"
        d.write_text(f"LIBRARY {mod}\nEXPORTS\n" + "\n".join(defs) + "\n")
        cmd = ["clang-cl", "/nologo", "/O1", "/LD", "/GS-", f"/imsvc{XWIN}/crt/include", f"/imsvc{XWIN}/sdk/include/ucrt",
               f"/imsvc{XWIN}/sdk/include/um", f"/imsvc{XWIN}/sdk/include/shared", str(c), f"/Fe{out / mod}",
               f"/Fo{out / (stem + '.obj')}", "-fuse-ld=lld-link", "/link", f"/def:{d}", "/noentry" if False else "/entry:DllMain",
               "/nodefaultlib", f"/libpath:{XWIN}/sdk/lib/um/x86_64", "kernel32.lib", "user32.lib"]
        r = subprocess.run(cmd, capture_output=True, text=True)
        status = "ok" if r.returncode == 0 else "FAILED\n" + r.stdout + r.stderr
        report.append(f"{mod}: {len(syms)} imports, {n_fwd} forwarded, {n_stub} stubbed: {status}")
    (out / "stubgen-report.txt").write_text("\n".join(report) + "\n")
    print("\n".join(report))
    return 0 if all(" ok" in r for r in report) else 1


if __name__ == "__main__":
    sys.exit(main())
