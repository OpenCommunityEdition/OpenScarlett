"""Generate default-fill code for every *_Function_Table struct in an SDK header.

The output is a C++ header that defines, for each table T, a function
    void xsl_fill_default(T* t)
which sets every leaf function pointer (including the nested base tables) to a
generated stub. Each stub logs "<Table>::<Entry>" the first few times it is
called and returns zero. Implementations then overwrite the entries they
support, so an unimplemented call always names itself in the log.

The output is derived from the licensed SDK header and is written to the build
directory only; it is never committed (hygiene rule 3).

Usage: gen_function_tables.py <d3d12_xs.h> <out.h>
"""
import re
import sys


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)


def parse(text):
    text = strip_comments(text)
    tables = {}
    order = []
    for m in re.finditer(r"\bstruct\s+(\w+_Function_Table)\s*\{", text):
        name = m.group(1)
        depth, i = 1, m.end()
        while depth:
            c = text[i]
            depth += (c == "{") - (c == "}")
            i += 1
        body = text[m.end():i - 1]
        entries = []
        # Keep preprocessor lines as separate statements.
        buf = ""
        for line in body.split("\n"):
            if line.strip().startswith("#"):
                if buf.strip():
                    entries.append(("stmt", buf))
                    buf = ""
                entries.append(("pp", line.strip()))
            else:
                buf += line + "\n"
                while ";" in buf:
                    stmt, buf = buf.split(";", 1)
                    entries.append(("stmt", stmt))
        out = []
        for kind, s in entries:
            if kind == "pp":
                out.append(("pp", s))
                continue
            s = " ".join(s.split())
            if not s:
                continue
            mb = re.fullmatch(r"(\w+_Function_Table)\s+(\w+)", s)
            if mb:
                out.append(("base", mb.group(1), mb.group(2)))
                continue
            mf = re.search(r"\(\s*\w*\s*\*\s*(\w+)\s*\)\s*\(", s)
            if mf:
                ret = s[:mf.start()].split()[-1] if s[:mf.start()].split() else ""
                params = [p.strip() for p in s[mf.end():s.rfind(")")].split(",") if p.strip()]
                # HRESULT entries: the parameter that receives a created object (a trailing T**).
                out_index = -1
                if ret == "HRESULT" and params and "**" in params[-1].replace(" ", ""):
                    out_index = len(params) - 1
                out.append(("fn", mf.group(1), ret, out_index))
                continue
            out.append(("unknown", s))
        tables[name] = out
        order.append(name)
    return tables, order


def main():
    src, dst = sys.argv[1], sys.argv[2]
    tables, order = parse(open(src, encoding="utf-8", errors="replace").read())
    lines = [
        "// Generated by tools/gen/gen_function_tables.py from the pinned SDK header. Do not commit.",
        "#pragma once",
        "#include \"xsl/stub.h\"",
        "",
    ]
    stub_id = 0
    stubs = []

    def emit_fill(table, prefix, path, body):
        nonlocal stub_id
        for e in tables[table]:
            if e[0] == "pp":
                body.append(e[1])
            elif e[0] == "base":
                emit_fill(e[1], prefix, path + e[2] + ".", body)
            elif e[0] == "fn":
                sid = stub_id
                stub_id += 1
                stubs.append((sid, f"{prefix}::{e[1]}"))
                if e[2] == "HRESULT" and e[3] < 10:
                    body.append(f"    t->{path}{e[1]} = reinterpret_cast<decltype(t->{path}{e[1]})>(&xsl_stub_hr<{sid}, {e[3]}>);")
                else:
                    body.append(f"    t->{path}{e[1]} = reinterpret_cast<decltype(t->{path}{e[1]})>(&xsl_stub<{sid}>);")
            else:
                body.append(f"    // unparsed: {e[1]}")

    fills = []
    for t in order:
        body = []
        emit_fill(t, t.replace("_Function_Table", ""), "", body)
        fills.append((t, body))

    lines.append("namespace xsl_gen {")
    lines.append("inline const char* const kStubNames[] = {")
    for sid, nm in stubs:
        lines.append(f'    "{nm}",')
    lines.append("};")
    lines.append("}")
    lines.append("template <int N> XSL_STUB_RET xsl_stub(void* self) { return xsl_stub_hit(N, xsl_gen::kStubNames[N], self); }")
    # HRESULT entries fail with E_NOTIMPL and clear the created-object pointer (argument OUTARG); x64
    # passes argument k in the same position whatever the other arguments' types.
    lines.append("template <int N, int OUTARG> long xsl_stub_hr(uintptr_t a0, uintptr_t a1, uintptr_t a2, uintptr_t a3, uintptr_t a4,")
    lines.append("                                           uintptr_t a5, uintptr_t a6, uintptr_t a7, uintptr_t a8, uintptr_t a9) {")
    lines.append("    xsl_stub_hit(N, xsl_gen::kStubNames[N], (void*)a0);")
    lines.append("    const long hr_ = xsl_stub_hresult();")
    lines.append("    if constexpr (OUTARG > 0) {")
    lines.append("        const uintptr_t args_[10] = {a0, a1, a2, a3, a4, a5, a6, a7, a8, a9};")
    lines.append("        if (hr_ < 0 && args_[OUTARG]) *(void**)args_[OUTARG] = nullptr;")
    lines.append("    }")
    lines.append("    return hr_;")
    lines.append("}")
    lines.append("")
    for t, body in fills:
        lines.append(f"inline void xsl_fill_default({t}* t) {{")
        lines += body
        lines.append("}")
    open(dst, "w").write("\n".join(lines) + "\n")
    print(f"{len(order)} tables, {stub_id} entries", file=sys.stderr)


if __name__ == "__main__":
    main()
