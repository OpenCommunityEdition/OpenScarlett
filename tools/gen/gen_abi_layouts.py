"""Generate the console D3D12 ABI layouts of older GDK editions (d3d12_xs.dll, xs_abi.cpp).

The console D3D12 vtables change between GDK releases, with methods inserted in the middle
(2026.04 added InsertGpuMarker/InsertTimingMarker to the queue at slot 14), and a title calls
the layout of the GDK it was built with; on a console it also ships the d3d12_xs.dll of that
GDK. The layer implements the layout of the pinned SDK and remaps its tables for older titles.

For each older header and each function table that differs from the pinned one, this writes the
pinned slot of every old slot (-1: no implementation, the slot logs and fails). Methods match
by name, the n-th occurrence of a repeated name to the n-th, and "Deprecated_" renames to their
old names. A table the older header lacks takes the layout of its nearest base table there.

Output is derived from the licensed SDKs and goes to the build directory only.

Usage: gen_abi_layouts.py <pinned d3d12_xs.h> <out.h> [EDITION=old/d3d12_xs.h ...] [--editions-dir DIR]
       (EDITION as in a title's .xbld "_xbld_edition_sdktype=GXDK,EDITION", e.g. 221000;
        DIR is tools/sdk/collect_editions.py's output: DIR/manifest.tsv names every edition's files)
"""
import hashlib
import os
import re
import sys

PINNED = int(os.environ.get("XSL_PINNED_GXDK_EDITION", "999999"))


def parse(path):
    src = open(path, errors="ignore").read()
    raw = {}
    for m in re.finditer(r"struct (\w+)_Function_Table\s*\{(.*?)\n\s*\};", src, re.S):
        items = []
        for it in re.finditer(r"^\s*(?:(\w+)_Function_Table\s+\w+\s*;|[\w\s\*]+?\(\s*D3DAPI\s*\*\s*(\w+)\s*\))", m.group(2), re.M):
            items.append(("base", it.group(1)) if it.group(1) else ("fn", it.group(2)))
        raw[m.group(1)] = items
    flat, chain = {}, {}

    def get(n):
        if n not in flat:
            out, bases = [], []
            for kind, v in raw.get(n, []):
                if kind == "base":
                    out += get(v)
                    bases = [v] + chain.get(v, [])
                else:
                    out.append(v)
            flat[n], chain[n] = out, bases
        return flat[n]

    for n in raw:
        get(n)
    return flat, chain


def keyed(names):
    seen, out = {}, []
    for n in names:
        base = n[len("Deprecated_"):] if n.startswith("Deprecated_") else n
        k = seen.get(base, 0)
        seen[base] = k + 1
        out.append((base, k))
    return out


def editions_from_dir(d):
    out = []
    for line in open(os.path.join(d, "manifest.tsv")).read().splitlines()[1:]:
        f = line.split("\t")
        if len(f) >= 3 and f[2] == "d3d12_xs.h" and f[1].isdigit():
            out.append(f"{f[1]}={os.path.join(d, f[0], f[2])}")
    return out


def main():
    args = sys.argv[1:]
    if "--editions-dir" in args:
        i = args.index("--editions-dir")
        extra = editions_from_dir(args[i + 1])
        args = args[:i] + args[i + 2:] + extra
    pinned, out_path, olds = args[0], args[1], args[2:]
    seen_ed = {}
    for spec in olds:  # one header per edition (the last named wins)
        seen_ed[spec.split("=", 1)[0]] = spec
    olds = sorted(seen_ed.values(), key=lambda s: int(s.split("=", 1)[0]))
    native, chain = parse(pinned)
    cache = {}  # header contents -> parsed tables (editions share headers)
    lines = ["// Generated by tools/gen/gen_abi_layouts.py from licensed SDK headers. Do not commit.", "#pragma once", "",
             "struct XslAbiTable { const char* name; unsigned slots; const short* map; };",
             "struct XslAbiEdition { unsigned edition; const XslAbiTable* tables; unsigned count; };", ""]
    editions = []
    for spec in olds:
        ed, path = spec.split("=", 1)
        if int(ed) >= PINNED:
            continue  # the pinned layout serves its own edition and later ones
        key = hashlib.sha256(open(path, "rb").read()).hexdigest()
        if key not in cache:
            cache[key] = parse(path)[0]
        old = cache[key]
        tables = []
        for name, nat in native.items():
            src_name = name if name in old else next((b for b in chain.get(name, []) if b in old), None)
            if src_name is None:
                continue
            o = old[src_name]
            if o == nat:
                continue
            idx = {k: i for i, k in enumerate(keyed(nat))}
            m = [idx.get(k, -1) for k in keyed(o)]
            if m == list(range(len(o))):
                continue  # the old table is a prefix of the pinned one: appended methods only
            arr = f"kAbi{ed}_{name}"
            lines.append(f"static const short {arr}[] = {{{', '.join(map(str, m))}}};  // {src_name}, {len(o)} slots")
            tables.append(f'{{"{name}", {len(o)}, {arr}}}')
        lines.append(f"static const XslAbiTable kAbi{ed}[] = {{{', '.join(tables) or '{nullptr, 0, nullptr}'}}};")
        lines.append("")
        editions.append(f"{{{int(ed)}u, kAbi{ed}, {len(tables)}u}}")
    lines.append(f"static const XslAbiEdition kXslAbiEditions[] = {{{', '.join(editions) or '{0, nullptr, 0}'}}};")
    lines.append(f"static const unsigned kXslAbiEditionCount = {len(editions)};")
    open(out_path, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
