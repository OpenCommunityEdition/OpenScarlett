"""Writes src/gpucode/buf_formats.inc: GFX10 unified buffer formats (the MTBUF format field) by
name, taken from LLVM's assembler (llvm-mc -mcpu=gfx1013) round-tripping every value."""
import re, subprocess, sys
from pathlib import Path

names = {1: "8_UNORM"}   # the default format, which LLVM prints without a format: operand
src = "\n".join(f"tbuffer_load_format_x v0, off, s[0:3], format:{i}, 0" for i in range(2, 128))
out = subprocess.run(["llvm-mc", "-arch=amdgcn", "-mcpu=gfx1013"], input=src, capture_output=True, text=True).stdout
lines = [l for l in out.splitlines() if "tbuffer_load_format_x" in l]
for i, l in zip(range(2, 128), lines):
    m = re.search(r"format:\[BUF_FMT_([A-Z0-9_]+)\]", l)
    if m: names[i] = m.group(1)
rows = [f'    {{{i}, "{n}"}},' for i, n in sorted(names.items())]
dst = Path(__file__).resolve().parents[2] / "src/gpucode/buf_formats.inc"
dst.write_text("// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by tools/gen/gen_buf_formats.py from LLVM's AMDGPU assembler (gfx1013). Do not edit.\n"
               "// GFX10 unified buffer format (MTBUF format field) -> name: component sizes, then numeric type.\n" + "\n".join(rows) + "\n")
print(f"{len(names)} formats -> {dst}")
