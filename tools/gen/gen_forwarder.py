"""Generate a forwarding DLL's thunks and module-definition file.

Each listed export becomes a jump through a table entry, filled when the DLL loads from the same
export of the system copy (resolved by the C++ side from GetSystemDirectoryW). Names in `--own`
are implemented by the DLL itself and only appear in the .def file.

Usage: gen_forwarder.py <exports.txt> <out.cpp> <out.def> <library name> [--own NAME ...]
"""
import sys


def main():
    args = sys.argv[1:]
    own = []
    if "--own" in args:
        i = args.index("--own")
        own = args[i + 1:]
        args = args[:i]
    exports_txt, out_cpp, out_def, lib = args
    names = [l.strip() for l in open(exports_txt) if l.strip() and not l.startswith("#")]
    names = [n for n in names if n not in own]
    with open(out_cpp, "w") as f:
        f.write("// Generated by tools/gen/gen_forwarder.py. Do not edit.\n")
        f.write(f"extern \"C\" void* xsl_fwd_table[{len(names)}];\n")
        f.write(f"extern \"C\" const char* const xsl_fwd_names[{len(names)}] = {{\n")
        for n in names:
            f.write(f'    "{n}",\n')
        f.write("};\n")
        f.write(f"extern \"C\" const unsigned xsl_fwd_count = {len(names)};\n")
        f.write("void* xsl_fwd_table[" + str(len(names)) + "];\n")
        f.write("asm(\n    \".intel_syntax noprefix\\n\" \".text\\n\"\n")
        for i, n in enumerate(names):
            f.write(f'    ".globl fwd_{n}\\n" "fwd_{n}:\\n" "  jmp qword ptr [rip + xsl_fwd_table + {8 * i}]\\n"\n')
        f.write(");\n")
    with open(out_def, "w") as f:
        f.write(f"LIBRARY {lib}\nEXPORTS\n")
        for n in names:
            f.write(f"    {n}=fwd_{n}\n")
        for n in own:
            f.write(f"    {n}\n")


if __name__ == "__main__":
    main()
